#!/usr/bin/env node
/**
 * Regenerate the README's contributors table from GitHub's own contributor
 * list, between the `contributors:start` / `contributors:end` markers.
 *
 * The table used to be hand-maintained, with a comment asking the next person
 * to copy a <td>. That is exactly the kind of instruction a merge forgets: the
 * CLI shipped in v3.11.0 and its author never appeared on the README.
 *
 * Roles are the one thing an API cannot know, so they stay hand-written in
 * .github/contributor-roles.json — a login → line map. A contributor with no
 * entry still gets a card, just without the role line, so nobody is ever
 * missing because someone forgot to describe them.
 *
 *   node scripts/update-contributors.mjs [--check]
 *
 * --check exits 1 when the README is out of date instead of writing it.
 */

import { readFileSync, writeFileSync } from "node:fs";

const REPO = process.env.GITHUB_REPOSITORY || "nodummd/nodum";
const START = "<!-- contributors:start -->";
const END = "<!-- contributors:end -->";

const token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN || "";
const headers = {
  Accept: "application/vnd.github+json",
  "User-Agent": "nodum-contributors",
  ...(token ? { Authorization: `Bearer ${token}` } : {}),
};

async function github(path) {
  const res = await fetch(`https://api.github.com${path}`, { headers });
  if (!res.ok) throw new Error(`GET ${path} → ${res.status} ${await res.text()}`);
  return res.json();
}

/** Every human who has contributed, most commits first. */
async function contributors() {
  const people = [];
  for (let page = 1; page <= 10; page++) {
    const batch = await github(`/repos/${REPO}/contributors?per_page=100&page=${page}`);
    people.push(...batch);
    if (batch.length < 100) break;
  }
  // Bots are credited in prose below the table, not as faces: an avatar row of
  // Dependabot is noise, and `type` alone misses the ones that register as
  // users, hence the name check too.
  return people.filter((p) => p.type !== "Bot" && !p.login.endsWith("[bot]"));
}

function card({ login, name, role }) {
  const display = name || login;
  const roleLine = role ? `\n      <sub>${role}</sub>\n      <br />` : "";
  return `    <td align="center" valign="top" width="170">
      <a href="https://github.com/${login}">
        <img src="https://github.com/${login}.png?size=200" width="96" height="96" alt="${display}" /><br />
        <sub><b>${display}</b></sub>
      </a>
      <br />${roleLine}
      <sub><a href="https://github.com/${login}">@${login}</a></sub>
    </td>`;
}

const roles = JSON.parse(readFileSync(new URL("../.github/contributor-roles.json", import.meta.url), "utf8"));

const people = await contributors();
// The maintainer leads, then most commits first — the order the API already
// returns, so a new contributor lands at the end rather than reshuffling faces.
const ordered = [
  ...people.filter((p) => roles[p.login]?.lead),
  ...people.filter((p) => !roles[p.login]?.lead),
];

const enriched = await Promise.all(
  ordered.map(async (p) => {
    const profile = await github(`/users/${p.login}`).catch(() => ({}));
    return { login: p.login, name: profile.name, role: roles[p.login]?.role };
  }),
);

// Six per row keeps the table readable on a phone-width README.
const rows = [];
for (let i = 0; i < enriched.length; i += 6) {
  rows.push(`  <tr>\n${enriched.slice(i, i + 6).map(card).join("\n")}\n  </tr>`);
}

const table = `${START}\n<!-- Generated by scripts/update-contributors.mjs — do not edit by hand.\n     Roles live in .github/contributor-roles.json. -->\n<table>\n${rows.join("\n")}\n</table>\n${END}`;

const path = new URL("../README.md", import.meta.url);
const readme = readFileSync(path, "utf8");
const from = readme.indexOf(START);
const to = readme.indexOf(END);
if (from === -1 || to === -1) throw new Error(`README is missing the ${START} / ${END} markers.`);

const updated = readme.slice(0, from) + table + readme.slice(to + END.length);

if (process.argv.includes("--check")) {
  if (updated !== readme) {
    console.error("README contributors table is out of date — run: node scripts/update-contributors.mjs");
    process.exit(1);
  }
  console.log(`contributors table is current (${enriched.length} people)`);
} else if (updated !== readme) {
  writeFileSync(path, updated);
  console.log(`updated: ${enriched.map((p) => p.login).join(", ")}`);
} else {
  console.log("no change");
}
