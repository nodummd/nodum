/**
 * Generate `src/components/import/brand-icons.ts` from simple-icons.
 *
 * Run with `npm run icons:gen`. Committed output, so `simple-icons` stays a
 * devDependency and none of its 3,400 icons reach the bundle — only the
 * fifteen or so this app actually draws.
 *
 * Several brands are deliberately absent from simple-icons because their
 * owners asked to be removed (Slack, Microsoft, Bear among them). Those are
 * not faked: the component falls back to a monogram tile, which identifies the
 * source just as clearly and invents no trademark.
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

import * as simpleIcons from "simple-icons";

const WANTED = [
  "obsidian",
  "notion",
  "evernote",
  "apple",
  "googlekeep",
  "roamresearch",
  "logseq",
  "joplin",
  "markdown",
  "discord",
  "telegram",
  "gmail",
  "anytype",
  "trilium",
  "maildotru",
];

const out = [];
const missing = [];

for (const slug of WANTED) {
  const key = `si${slug.charAt(0).toUpperCase()}${slug.slice(1)}`;
  const icon = simpleIcons[key];
  if (!icon) {
    missing.push(slug);
    continue;
  }
  out.push({ slug, path: icon.path, title: icon.title });
}

const header = `// GENERATED by scripts/gen-brand-icons.mjs — do not edit by hand.
// Run \`npm run icons:gen\` to refresh. Paths are from simple-icons (CC0);
// the marks remain their owners' trademarks and are used here only to identify
// the product a person is importing from.
//
// Brands absent from simple-icons (their owners requested removal) are not
// included and fall back to a monogram tile in <BrandIcon>:
// ${missing.length ? missing.join(", ") : "none"}
`;

const body = `
export interface BrandGlyph {
  /** 24×24 viewBox path data. */
  path: string;
  title: string;
}

export const BRAND_GLYPHS: Record<string, BrandGlyph> = ${JSON.stringify(
  Object.fromEntries(out.map((i) => [i.slug, { path: i.path, title: i.title }])),
  null,
  2,
)};
`;

const target = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "components",
  "import",
  "brand-icons.ts",
);
writeFileSync(target, header + body);
console.log(`wrote ${out.length} glyphs → ${target}`);
if (missing.length) console.log(`monogram fallback: ${missing.join(", ")}`);
